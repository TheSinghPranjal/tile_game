/// Picture layouts: boards whose tiles are arranged to look like a letter,
/// a number, an animal or an object.
///
/// Each shape is drawn as ASCII art. `#` is a tile on the bottom layer and
/// `.` is empty. Upper layers are derived by the layout builder's stacking
/// rule, so they keep the silhouette and only sit where they are supported.
/// Art is kept at most 9 cells wide so tiles stay readable on phones.
library;

enum ShapeCategory {
  letter('Letter'),
  number('Number'),
  animal('Animal'),
  object('Object');

  final String label;
  const ShapeCategory(this.label);
}

class ShapeArt {
  final String name;
  final ShapeCategory category;
  final List<String> rows;

  const ShapeArt(this.name, this.category, this.rows);

  int get width => rows.fold(0, (w, r) => r.length > w ? r.length : w);
  int get height => rows.length;

  /// Bottom-layer cells as (column, row).
  Set<(int, int)> get cells => {
        for (var r = 0; r < rows.length; r++)
          for (var c = 0; c < rows[r].length; c++)
            if (rows[r][c] == '#') (c, r),
      };

  int get cellCount => cells.length;

  /// Title shown in the top bar, e.g. "Letter A" or "Cat".
  String get title => switch (category) {
        ShapeCategory.letter => 'Letter $name',
        ShapeCategory.number => 'Number $name',
        _ => name,
      };
}

